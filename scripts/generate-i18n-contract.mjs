import {readFileSync,writeFileSync} from 'node:fs';
const contract = JSON.parse(readFileSync('src/shared/i18n/contract/locales.json','utf8'));
const file = 'src/apps/mobile/android/app/src/main/kotlin/com/openbitfun/mobile/app/platform/GeneratedLocaleContract.kt';
const expected = `// Generated by scripts/generate-i18n-contract.mjs. Do not edit.
package com.openbitfun.mobile.app.platform

internal const val DEFAULT_APP_LANGUAGE_TAG = "${contract.surfaceDefaults.android}"
`;
if(process.argv.includes('--check')) {
 if(readFileSync(file,'utf8')!==expected) throw new Error('Native locale projection is stale; run pnpm run i18n:generate.');
} else writeFileSync(file,expected);
